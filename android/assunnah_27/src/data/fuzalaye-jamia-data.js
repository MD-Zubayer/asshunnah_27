export const allFuzalaList = Object.entries(fuzalayeJamiaData).flatMap(([jamat, jamatDistricts]) =>
  Object.entries(jamatDistricts).flatMap(([district, students]) =>
    students.map((student) => ({ ...student, jamat, district }))
  )
);

export const fuzalayeJamiaByDistrict = allFuzalaList.reduce((acc, student) => {
  if (!acc[student.district]) acc[student.district] = [];
  acc[student.district].push(student);
  return acc;
}, {});

