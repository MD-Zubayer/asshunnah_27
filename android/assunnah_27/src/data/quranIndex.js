export function getParaByPage(page) {
  const p = Number(page) || 1;
  if (p < 2) return QURAN_PARAS[0];
  let found = QURAN_PARAS[0];
  for (let i = QURAN_PARAS.length - 1; i >= 0; i--) {
    if (p >= QURAN_PARAS[i].page) {
      found = QURAN_PARAS[i];
      break;
    }
  }
  return found;
}

export function getSurahByPage(page) {
  const p = Number(page) || 1;
  if (p < 2) return QURAN_SURAHS[0];
  let found = QURAN_SURAHS[0];
  for (let i = QURAN_SURAHS.length - 1; i >= 0; i--) {
    if (p >= QURAN_SURAHS[i].page) {
      found = QURAN_SURAHS[i];
      break;
    }
  }
  return found;
}

export function getQuranPageInfo(page) {
  const p = Math.max(1, Math.min(TOTAL_QURAN_PAGES, Number(page) || 1));
  const para = getParaByPage(p);
  const surah = getSurahByPage(p);
  const sijdah = QURAN_SIJDAHS.find((s) => s.page === p);
  return {
    page: p,
    para,
    surah,
    sijdah: sijdah || null,
    isDuaKhatmulQuran: p >= 612,
  };
}
